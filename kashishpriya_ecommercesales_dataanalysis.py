import os
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd
import seaborn as sns


# Visualization styling
sns.set_theme(style="whitegrid")
os.makedirs("output_images", exist_ok=True)

# Load the dataset
csv_filename = "/content/ecommerce_sales_analytics_5000.csv"
df = pd.read_csv(csv_filename)

print("--- Shape & Initial Info ---")
print(f"Dataset Shape: {df.shape}")
print(df.info())
print("\n--- Missing Values Count ---")
print(df.isnull().sum())

# Convert order_date to datetime
df["order_date"] = pd.to_datetime(df["order_date"], errors="coerce")

# Impute or handle missing values (e.g., median for customer_rating if nulls exist)
if df["customer_rating"].isnull().sum() > 0:
  rating_median = df["customer_rating"].median()
  df["customer_rating"].fillna(rating_median, inplace=True)

# Drop any accidental duplicates
df.drop_duplicates(inplace=True)

# Feature Engineering
df["order_month"] = df["order_date"].dt.strftime("%Y-%m")
df["order_day_name"] = df["order_date"].dt.day_name()

print("Cleaned Dataset Shape:", df.shape)
print("Remaining Null Values:\n", df.isnull().sum())



# 1. Total Revenue by Product Category
plt.figure(figsize=(9, 5))
cat_rev = (
    df.groupby("product_category")["revenue"]
    .sum()
    .sort_values(ascending=False)
    .reset_index()
)
sns.barplot(data=cat_rev, x="revenue", y="product_category", palette="Blues_r")
plt.title("Total Revenue by Product Category", fontsize=14, weight="bold")
plt.xlabel("Total Revenue ($)")
plt.ylabel("Category")
plt.tight_layout()
plt.savefig("output_images/category_revenue.png", dpi=300)
plt.close()

# 2. Regional Sales & Quantity
plt.figure(figsize=(8, 4.5))
reg_sales = (
    df.groupby("region")["revenue"]
    .sum()
    .sort_values(ascending=False)
    .reset_index()
)
sns.barplot(data=reg_sales, x="region", y="revenue", palette="viridis")
plt.title("Total Revenue by Region", fontsize=14, weight="bold")
plt.xlabel("Region")
plt.ylabel("Total Revenue ($)")
plt.tight_layout()
plt.savefig("output_images/regional_revenue.png", dpi=300)
plt.close()

# 3. Delivery Days vs Customer Rating
plt.figure(figsize=(8, 4.5))
sns.boxplot(
    data=df,
    x="customer_rating",
    y="delivery_days",
    palette="coolwarm",
    hue="customer_rating",
    legend=False,
)
plt.title("Delivery Days vs. Customer Rating", fontsize=14, weight="bold")
plt.xlabel("Customer Rating (Stars)")
plt.ylabel("Delivery Days")
plt.tight_layout()
plt.savefig("output_images/delivery_vs_rating.png", dpi=300)
plt.close()

# 4. Correlation Heatmap
plt.figure(figsize=(8, 5))
numeric_cols = [
    "quantity",
    "unit_price",
    "discount",
    "delivery_days",
    "customer_rating",
    "revenue",
]
sns.heatmap(
    df[numeric_cols].corr(), annot=True, cmap="mako", fmt=".2f", linewidths=0.5
)
plt.title("Feature Correlation Matrix", fontsize=14, weight="bold")
plt.tight_layout()
plt.savefig("output_images/correlation_matrix.png", dpi=300)
plt.close()

print("All charts successfully generated and saved to 'output_images/'")